import Link from 'next/link';
import { AttendanceBadge, Card, CardBody, CardHeader, CardTitle, EmptyState } from '@attend/ui';
import { apiFetch, requireRole } from '@/lib/api';
import { StartSessionButton } from './StartSessionButton';

export const metadata = { title: 'Today · Attend' };

interface SessionSummary {
  id: string;
  courseCode: string;
  courseTitle: string;
  roomName: string | null;
  startsAt: string;
  checkinOpensAt: string;
  checkinClosesAt: string;
  status: string;
  enrolledCount: number;
  presentCount: number;
  lateCount: number;
  flaggedCount: number;
}

export default async function LecturerToday() {
  await requireRole('lecturer');
  const { sessions } = await apiFetch<{ sessions: SessionSummary[] }>('/api/v1/lecturer/today');

  return (
    <div className="space-y-4">
      <div>
        <h1 className="text-xl font-semibold">Today</h1>
        <p className="text-sm text-slate-600">Start a session to show the rotating QR code to the room.</p>
      </div>

      {sessions.length === 0 ? (
        <EmptyState title="No sessions today" description="Sessions come from the timetable generated by the administrator." />
      ) : (
        <div className="grid gap-3 md:grid-cols-2">
          {sessions.map((session) => (
            <Card key={session.id}>
              <CardHeader className="flex items-start justify-between">
                <div>
                  <CardTitle>
                    {session.courseCode} <span className="font-normal text-slate-500">{session.courseTitle}</span>
                  </CardTitle>
                  <p className="mt-1 text-xs text-slate-500">
                    {new Date(session.startsAt).toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit' })}
                    {session.roomName ? ` · ${session.roomName}` : ''} · {session.enrolledCount} enrolled
                  </p>
                </div>
                <span className="text-xs uppercase tracking-wide text-slate-500">{session.status}</span>
              </CardHeader>
              <CardBody className="space-y-3">
                <div className="flex gap-2 text-xs">
                  <AttendanceBadge status="present" />
                  <span className="text-slate-600">{session.presentCount}</span>
                  <AttendanceBadge status="late" />
                  <span className="text-slate-600">{session.lateCount}</span>
                  <AttendanceBadge status="present_flagged" />
                  <span className="text-slate-600">{session.flaggedCount}</span>
                </div>
                {session.status === 'scheduled' ? (
                  <StartSessionButton sessionId={session.id} />
                ) : (
                  <Link
                    href={`/lecturer/sessions/${session.id}`}
                    className="inline-flex min-h-11 items-center rounded-lg bg-slate-900 px-4 text-sm font-medium text-white"
                  >
                    Open live session
                  </Link>
                )}
              </CardBody>
            </Card>
          ))}
        </div>
      )}
    </div>
  );
}
